import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const rootDir = path.resolve(__dirname, '..');

const stacksDir = path.join(rootDir, 'stacks');
const registryDir = path.join(rootDir, 'registry');
const distDir = path.join(rootDir, 'dist');
const localCursorRulesDir = path.join(rootDir, '.cursor', 'rules');

console.log('🚀 Building next-agent-pack distribution bundles...');

if (!fs.existsSync(distDir)) {
  fs.mkdirSync(distDir, { recursive: true });
}

if (!fs.existsSync(localCursorRulesDir)) {
  fs.mkdirSync(localCursorRulesDir, { recursive: true });
}

function stripFrontmatter(content) {
  if (!content.startsWith('---')) return content;
  const secondIndex = content.indexOf('\n---', 3);
  if (secondIndex === -1) return content;
  return content.substring(secondIndex + 4).trim();
}

const stacks = fs.readdirSync(stacksDir);

for (const stackName of stacks) {
  const stackPath = path.join(stacksDir, stackName);
  if (!fs.statSync(stackPath).isDirectory()) continue;

  const manifestPath = path.join(stackPath, 'manifest.json');
  if (!fs.existsSync(manifestPath)) continue;

  const manifest = JSON.parse(fs.readFileSync(manifestPath, 'utf8'));
  const targetDistName = stackName === 'next15-shadcn-minimal' ? 'next15-shadcn' : stackName;
  const targetDistDir = path.join(distDir, targetDistName);

  if (!fs.existsSync(targetDistDir)) {
    fs.mkdirSync(targetDistDir, { recursive: true });
  }

  console.log(`📦 Processing stack: ${manifest.name} -> dist/${targetDistName}`);

  const combinedSections = [];

  for (const [sourceRelative, distFileName] of Object.entries(manifest.distMapping)) {
    const sourcePath = path.join(registryDir, sourceRelative);
    if (!fs.existsSync(sourcePath)) {
      console.error(`❌ Source rule not found: ${sourcePath}`);
      process.exit(1);
    }

    const content = fs.readFileSync(sourcePath, 'utf8');
    const targetPath = path.join(targetDistDir, distFileName);
    fs.writeFileSync(targetPath, content, 'utf8');
    console.log(`  ✓ [Cursor] Written ${distFileName}`);

    // If minimal stack, dogfood into local .cursor/rules as well
    if (stackName === 'next15-shadcn-minimal') {
      const localRulePath = path.join(localCursorRulesDir, distFileName);
      fs.writeFileSync(localRulePath, content, 'utf8');
    }

    // Strip frontmatter for AGENTS.md / Skill bundle
    const markdownBody = stripFrontmatter(content);
    combinedSections.push(markdownBody);
  }

  // 1. Generate Antigravity AGENTS.md
  const agentsMdContent = `# ${manifest.name}

> Auto-generated by \`next-agent-pack\` for Antigravity, Gemini Code Assist, and Markdown-compatible AI agents.

${combinedSections.join('\n\n---\n\n')}
`;

  const distAgentsMdPath = path.join(targetDistDir, 'AGENTS.md');
  fs.writeFileSync(distAgentsMdPath, agentsMdContent, 'utf8');
  console.log(`  ✓ [Antigravity] Generated AGENTS.md`);

  // Dogfood AGENTS.md to root if minimal stack
  if (stackName === 'next15-shadcn-minimal') {
    const rootAgentsMdPath = path.join(rootDir, 'AGENTS.md');
    fs.writeFileSync(rootAgentsMdPath, agentsMdContent, 'utf8');
  }

  // 2. Generate Antigravity Skill format
  const skillDir = path.join(targetDistDir, 'skills', 'next-agent-pack');
  if (!fs.existsSync(skillDir)) {
    fs.mkdirSync(skillDir, { recursive: true });
  }

  const skillContent = `---
name: next-agent-pack
description: Best practices and rules for Next.js 15 App Router, React 19 hooks (useActionState, useOptimistic), Tailwind CSS tokens, and shadcn/ui components.
---

# Next.js 15 & React 19 Engineering Skill Pack

${combinedSections.join('\n\n---\n\n')}
`;

  const distSkillPath = path.join(skillDir, 'SKILL.md');
  fs.writeFileSync(distSkillPath, skillContent, 'utf8');
  console.log(`  ✓ [Antigravity] Generated skills/next-agent-pack/SKILL.md`);
}

console.log('✅ Build completed successfully!');
